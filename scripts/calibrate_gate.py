#!/usr/bin/env python3
"""Gate calibration from the golden question set.

For every golden question (in and out of scope) compute:
  - top-1 dense score, top-1 fusion score
  - number of query content words found by FTS5 in top-3 chunks

Print min/median/max of top-1 dense score for in-scope vs out-of-scope,
plus text histograms.

Evaluate three gates over a threshold grid:
  (1) dense score only
  (2) dense score AND at least one content-word match in top-3 chunks
  (3) fusion score only

For each threshold print: in-scope acceptance rate, out-of-scope rejection rate.
Recommend the gate and threshold that gives out-of-scope rejection >= 98%
with the highest in-scope acceptance.

Write assets/config_calibrated.json (generated by CI, gitignored).
"""
import json
import os
import re
import sqlite3
import sys

import numpy as np

DB_PATH = os.path.join("app", "src", "main", "assets", "books_knowledge.db")
EMBEDDINGS_BIN = os.path.join("app", "src", "main", "assets", "embeddings.bin")
EMBEDDINGS_META = os.path.join("app", "src", "main", "assets", "embeddings_meta.json")
GOLDEN_PATH = os.path.join("eval", "golden_questions.draft.jsonl")
ALIASES_PATH = os.path.join("app", "src", "main", "assets", "medical_aliases.json")
CONFIG_OUT = os.path.join("app", "src", "main", "assets", "config_calibrated.json")

EMBED_DIM = 384
STOPWORDS = {
    "the", "a", "an", "and", "or", "but", "in", "on", "at", "to", "for", "of",
    "with", "by", "from", "as", "is", "are", "was", "were", "be", "been", "being",
    "have", "has", "had", "do", "does", "did", "will", "would", "could", "should",
    "may", "might", "can", "this", "that", "these", "those", "i", "you", "he",
    "she", "it", "we", "they", "what", "how", "when", "where", "why", "who",
    "ما", "هي", "كيف", "ما هي", "كيف يتم", "ما هي أسباب", "كيف يتم علاج",
}


def load_embeddings():
    with open(EMBEDDINGS_META, "r", encoding="utf-8") as f:
        meta = json.load(f)
    dim = meta["dim"]
    rows = meta["rows"]
    mat = np.fromfile(EMBEDDINGS_BIN, dtype=np.float32).reshape(rows, dim)
    return mat


def load_golden():
    questions = []
    with open(GOLDEN_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                questions.append(json.loads(line))
    return questions


def load_aliases():
    if not os.path.exists(ALIASES_PATH):
        return {}
    with open(ALIASES_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def safe_fts_query(query):
    tokens = [t for t in re.split(r"\s+", query.strip()) if t]
    quoted = [f'"{t}"' for t in tokens]
    if not quoted:
        return ""
    if len(quoted) == 1:
        return quoted[0]
    return " OR ".join(quoted)


def fts_search(cur, query, top_k=5):
    fts_q = safe_fts_query(query)
    if not fts_q:
        return []
    cur.execute(
        "SELECT b.name, c.page, c.text, bm25(chunks_fts) AS rank "
        "FROM chunks_fts f "
        "JOIN chunks c ON c.id = f.rowid "
        "JOIN books b ON b.id = c.book_id "
        "WHERE f.text MATCH ? "
        "ORDER BY rank LIMIT ?",
        (fts_q, top_k),
    )
    return cur.fetchall()


def dense_search(query_vec, embeddings, chunk_meta, top_k=5):
    scores = embeddings @ query_vec
    top_idx = np.argsort(-scores)[:top_k]
    results = []
    for idx in top_idx:
        cid, name, page, text = chunk_meta[idx]
        results.append((name, page, text, float(scores[idx])))
    return results


def rrf_fuse(dense_results, fts_results, k=60, top_k=5):
    scores = {}
    dense_keys = [(r[0], r[1]) for r in dense_results]
    fts_keys = [(r[0], r[1]) for r in fts_results]
    for rank, key in enumerate(dense_keys):
        scores[key] = scores.get(key, 0.0) + 1.0 / (k + rank + 1)
    for rank, key in enumerate(fts_keys):
        scores[key] = scores.get(key, 0.0) + 1.0 / (k + rank + 1)
    text_lookup = {}
    for r in dense_results + fts_results:
        text_lookup[(r[0], r[1])] = r[2]
    sorted_keys = sorted(scores.items(), key=lambda x: -x[1])[:top_k]
    return [(key[0], key[1], text_lookup.get(key, ""), score) for key, score in sorted_keys]


def content_words(query):
    words = [w.lower() for w in re.findall(r"\w+", query) if w.lower() not in STOPWORDS and len(w) > 2]
    return words


def count_keyword_hits(cur, query, top_chunks_texts):
    words = content_words(query)
    if not words:
        return 0
    hits = 0
    for text in top_chunks_texts:
        text_lower = text.lower()
        for w in words:
            if w in text_lower:
                hits += 1
                break
    return hits


def hist(values, bins=10):
    if not values:
        return "  (no data)"
    lo, hi = min(values), max(values)
    if lo == hi:
        return f"  [{lo:.3f}]: {len(values)}"
    edges = [lo + (hi - lo) * i / bins for i in range(bins + 1)]
    counts = [0] * bins
    for v in values:
        for i in range(bins):
            if edges[i] <= v < edges[i + 1] or (i == bins - 1 and v == hi):
                counts[i] += 1
                break
    lines = []
    for i in range(bins):
        bar = "#" * counts[i]
        lines.append(f"  [{edges[i]:.3f}-{edges[i+1]:.3f}]: {bar} ({counts[i]})")
    return "\n".join(lines)


def main():
    if not os.path.exists(DB_PATH):
        print(f"ERROR: {DB_PATH} not found.", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(EMBEDDINGS_BIN):
        print(f"ERROR: {EMBEDDINGS_BIN} not found.", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(GOLDEN_PATH):
        print(f"ERROR: {GOLDEN_PATH} not found.", file=sys.stderr)
        sys.exit(1)

    embeddings = load_embeddings()
    questions = load_golden()
    aliases = load_aliases()

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    chunk_meta = cur.execute(
        "SELECT c.id, b.name, c.page, c.text FROM chunks c JOIN books b ON b.id = c.book_id ORDER BY c.id"
    ).fetchall()
    id_to_index = {cid: i for i, (cid, _, _, _) in enumerate(chunk_meta)}

    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from embedding_common import embed_texts  # noqa: E402

    # Compute scores for all questions.
    records = []
    for q in questions:
        query_text = q["q"]
        if q["lang"] == "ar":
            # Apply alias expansion.
            for ar_term, en_terms in aliases.items():
                if ar_term in query_text:
                    for en in en_terms:
                        if en not in query_text:
                            query_text += " " + en

        q_vec = embed_texts([query_text], kind="query")[0]
        dense_res = dense_search(q_vec, embeddings, chunk_meta, top_k=3)
        fts_res = fts_search(cur, query_text, top_k=3)
        fusion_res = rrf_fuse(dense_res, fts_res, top_k=3)

        top3_texts = [r[2] for r in dense_res]
        kw_hits = count_keyword_hits(cur, query_text, top3_texts)

        records.append({
            "q": q["q"],
            "lang": q["lang"],
            "in_scope": q["in_scope"],
            "dense_top1_score": dense_res[0][3] if dense_res else 0.0,
            "fusion_top1_score": fusion_res[0][3] if fusion_res else 0.0,
            "kw_hits_top3": kw_hits,
        })

    in_scope = [r for r in records if r["in_scope"]]
    out_scope = [r for r in records if not r["in_scope"]]

    dense_in = [r["dense_top1_score"] for r in in_scope]
    dense_out = [r["dense_top1_score"] for r in out_scope]
    fusion_in = [r["fusion_top1_score"] for r in in_scope]
    fusion_out = [r["fusion_top1_score"] for r in out_scope]

    print("\n=== Score Statistics ===")
    print(f"\nTop-1 dense score - In-scope (n={len(in_scope)}):")
    print(f"  min={min(dense_in):.4f} median={np.median(dense_in):.4f} max={max(dense_in):.4f}")
    print(hist(dense_in))
    print(f"\nTop-1 dense score - Out-of-scope (n={len(out_scope)}):")
    print(f"  min={min(dense_out):.4f} median={np.median(dense_out):.4f} max={max(dense_out):.4f}")
    print(hist(dense_out))

    print(f"\nTop-1 fusion score - In-scope (n={len(in_scope)}):")
    print(f"  min={min(fusion_in):.4f} median={np.median(fusion_in):.4f} max={max(fusion_in):.4f}")
    print(hist(fusion_in))
    print(f"\nTop-1 fusion score - Out-of-scope (n={len(out_scope)}):")
    print(f"  min={min(fusion_out):.4f} median={np.median(fusion_out):.4f} max={max(fusion_out):.4f}")
    print(hist(fusion_out))

    # Gate evaluation grid.
    print("\n=== Gate Comparison ===")
    print("| Gate | Threshold | In-scope acceptance | Out-of-scope rejection |")
    print("|---|---|---|---|---|")

    best = None  # (rejection, acceptance, gate_name, threshold)

    # Gate 1: dense score only.
    for t in np.arange(0.50, 0.95, 0.01):
        acc = sum(1 for r in in_scope if r["dense_top1_score"] >= t) / len(in_scope)
        rej = sum(1 for r in out_scope if r["dense_top1_score"] < t) / len(out_scope)
        print(f"| dense only | {t:.2f} | {acc:.3f} | {rej:.3f} |")
        if rej >= 0.98 and (best is None or acc > best[1]):
            best = (rej, acc, "dense_only", float(t))

    # Gate 2: dense score AND at least one keyword hit.
    for t in np.arange(0.50, 0.95, 0.01):
        acc = sum(1 for r in in_scope if r["dense_top1_score"] >= t and r["kw_hits_top3"] >= 1) / len(in_scope)
        rej = sum(1 for r in out_scope if not (r["dense_top1_score"] >= t and r["kw_hits_top3"] >= 1)) / len(out_scope)
        print(f"| dense+keyword | {t:.2f} | {acc:.3f} | {rej:.3f} |")
        if rej >= 0.98 and (best is None or acc > best[1]):
            best = (rej, acc, "dense_plus_keyword", float(t))

    # Gate 3: fusion score only.
    for t in np.arange(0.00, 0.04, 0.001):
        acc = sum(1 for r in in_scope if r["fusion_top1_score"] >= t) / len(in_scope)
        rej = sum(1 for r in out_scope if r["fusion_top1_score"] < t) / len(out_scope)
        print(f"| fusion only | {t:.3f} | {acc:.3f} | {rej:.3f} |")
        if rej >= 0.98 and (best is None or acc > best[1]):
            best = (rej, acc, "fusion_only", float(t))

    print("\n=== Recommendation ===")
    if best:
        rej, acc, gate, threshold = best
        print(f"Recommended gate: {gate}")
        print(f"Threshold: {threshold}")
        print(f"In-scope acceptance: {acc:.3f}")
        print(f"Out-of-scope rejection: {rej:.3f}")
        recommended = {
            "gate": gate,
            "dense_threshold": threshold if gate == "dense_only" else 0.62,
            "min_keyword_hits": 1 if gate == "dense_plus_keyword" else 0,
            "fusion_threshold": threshold if gate == "fusion_only" else 0.0,
            "calibrated_on": "draft",
        }
    else:
        print("No gate achieves out-of-scope rejection >= 98%.")
        print("Best achievable numbers would need to be reported from the grid above.")
        recommended = {
            "gate": "none",
            "dense_threshold": 0.62,
            "min_keyword_hits": 0,
            "fusion_threshold": 0.0,
            "calibrated_on": "draft",
        }

    # Write config.
    os.makedirs(os.path.dirname(CONFIG_OUT), exist_ok=True)
    with open(CONFIG_OUT, "w", encoding="utf-8") as f:
        json.dump(recommended, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"\nConfig written to {CONFIG_OUT}")
    conn.close()


if __name__ == "__main__":
    main()
